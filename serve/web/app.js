  const key = `${gpus.map((g) => g.bus).join(",")}|${sockets.map((s) => s.node).join(",")}`;
  if (key === devicesKey) return;
  devicesKey = key;
  const box = $("devices");
  box.hidden = !gpus.length && !sockets.length;
  const row = (id, label) => `<dt>${esc(label)}</dt><dd id="${id}">–</dd>`;
